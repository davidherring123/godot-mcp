type CreateParams struct {
	Resource   string                     `json:"resource" jsonschema:"minLength=1,description=New resource file path such as res://materials/metal.tres, ending in .tres or .res. Fails if the file already exists."`
	Type       string                     `json:"type" jsonschema:"minLength=1,description=Resource class to instantiate, such as StandardMaterial3D. Global script classes are supported."`
	Properties map[string]json.RawMessage `json:"properties,omitempty" jsonschema_description:"Optional property values, including resource references, inline resources such as {\"type\":\"BoxMesh\",\"properties\":{\"size\":{\"x\":1,\"y\":1,\"z\":1}}}, and packed arrays. ShaderMaterial shader assignment is staged before shader_parameter values."`
}

type CreateResult struct {
	Resource      string                     `json:"resource" jsonschema:"description=Resource path that was written."`
	Type          string                     `json:"type" jsonschema:"description=Actual resource type; the global script class name when a script is attached."`
	Properties    map[string]json.RawMessage `json:"properties" jsonschema:"description=Actual property values after applying the requested properties."`
	UID           string                     `json:"uid,omitempty" jsonschema:"description=UID already stored in the written file, when the editor assigned one. It is not newly generated by this action."`
	UIDRegistered bool                       `json:"uid_registered" jsonschema:"description=Whether the editor registered the file's UID in its filesystem cache before this action returned. False means the file exists on disk but a separate process may not resolve its UID yet."`
	Note          string                     `json:"note,omitempty" jsonschema:"description=Present only when the file was written but its UID could not be registered before the bounded wait expired. Do not create the file again; run filesystem.scan and retry the dependent operation."`
}

